export function seed(store: Store) {
  if (store.one('SELECT id FROM products LIMIT 1')) return;
  store.transaction(() => {
    for (const [sku, name, category, retail, cost, stock, age, tags] of products) {
      store.run(
        'INSERT INTO products(id,sku,name,description,category,cost,retail,floor,stock,age_days,quality,discount_bps,margin_bps,clearance,tags) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)',
        randomUUID(),
        sku,
        name,
        `Synthetic demo product. ${tags}. No physical goods are shipped.`,
        category,
        cost,
        retail,
        Math.ceil(retail * 0.65),
        stock,
        age,
        65 + (age % 31),
        2000,
        2500,
        1,
        tags,
      );
    }
  });
}
